/** 关键词命中：命中越多越优先（至少命中 1 个） */
export function findLocalAnswer(question: string): string | null {
  const text = question.toLowerCase();
  let best: { score: number; answer: string } | null = null;

  for (const item of LOCAL_ANSWERS) {
    const score = item.keywords.reduce((sum, keyword) => (text.includes(keyword) ? sum + 1 : sum), 0);
    if (score > 0 && (!best || score > best.score)) {
      best = { score, answer: item.answer };
    }
  }

  return best?.answer ?? null;
}
